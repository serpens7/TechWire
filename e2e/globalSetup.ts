import { execSync } from 'node:child_process';
import { resolve } from 'node:path';

/**
 * Приводит БД к исходному состоянию перед прогоном e2e.
 *
 * Нужно потому, что тесты теперь пишут по-настоящему: раньше записи глушились
 * через page.route, чтобы не портить закоммиченный db.json, и проверялось лишь
 * то, что фронт отправил правильный запрос. С настоящей БД глушить нечего —
 * тесты проверяют, что комментарий действительно сохранился, а оценка
 * действительно проставилась.
 *
 * Цена — прогон должен начинаться с чистого состояния: тест оценки требует,
 * чтобы пользователь статью ещё не оценивал, а сам же это состояние и ломает.
 *
 * Чистим сидом с --fresh (DELETE + повторный засев), а не `prisma migrate
 * reset`: последний дропает базу целиком и падает, если к ней уже подключён
 * запущенный бэкенд.
 *
 * ВНИМАНИЕ: всё, что вы создали в приложении руками, будет стёрто. Данные
 * полностью восстанавливаются из json-server/db.json, так что потерять можно
 * только то, что добавили сами во время разработки.
 */
export default function globalSetup(): void {
    const server = resolve(__dirname, '../server');

    console.log('[e2e] сброс БД к состоянию из db.json…');
    execSync('npm run db:seed:fresh', { cwd: server, stdio: 'inherit' });
}
